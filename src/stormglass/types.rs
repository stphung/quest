// ── Exchange UI state ──────────────────────────────────────────────────

/// Phase of the Stormglass Exchange overlay.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExchangePhase {
    Menu,
    InvokeTrial,
    ChronoSurge,
}

/// A single trial option generated by Invoke Trial.
#[derive(Debug, Clone)]
pub struct TrialOption {
    pub challenge_type: ChallengeType,
    pub display_name: String,
}

/// UI state for the Stormglass Exchange overlay.
#[derive(Debug, Clone)]
pub struct ExchangeUiState {
    pub open: bool,
    pub selected_item: usize,
    pub phase: ExchangePhase,
    pub trial_options: Vec<TrialOption>,
    pub trial_selected: usize,
    pub surge_selected: usize,
}

impl ExchangeUiState {
    pub fn new() -> Self {
        Self {
            open: false,
            selected_item: 0,
            phase: ExchangePhase::Menu,
            trial_options: Vec::new(),
            trial_selected: 0,
            surge_selected: 0,
        }
    }

    pub fn open(&mut self) {
        self.open = true;
        self.selected_item = 0;
        self.phase = ExchangePhase::Menu;
        self.trial_options.clear();
        self.trial_selected = 0;
        self.surge_selected = 0;
    }

    pub fn close(&mut self) {
        self.open = false;
        self.phase = ExchangePhase::Menu;
        self.trial_options.clear();
        self.trial_selected = 0;
        self.surge_selected = 0;
    }
}

impl Default for ExchangeUiState {
    fn default() -> Self {
        Self::new()
    }
}

