/// Tracks an active Chrono Surge in progress.
pub struct ChronoSurgeState {
    pub ticks_remaining: u64,
    pub ticks_total: u64,
    /// Ticks per 100ms frame — computed so animation lasts CHRONO_SURGE_ANIMATION_SECONDS.
    pub batch_size: u64,
    pub kills: u64,
    pub levels_gained: u32,
    pub items_equipped: u32,
}

impl ChronoSurgeState {
    pub fn new(ticks: u64) -> Self {
        // 10 frames per second * animation seconds = total animation frames
        let animation_frames = CHRONO_SURGE_ANIMATION_SECONDS * 10;
        let batch_size = (ticks / animation_frames).max(1);
        Self {
            ticks_remaining: ticks,
            ticks_total: ticks,
            batch_size,
            kills: 0,
            levels_gained: 0,
            items_equipped: 0,
        }
    }

    /// Progress as a fraction 0.0..=1.0.
    pub fn progress(&self) -> f64 {
        if self.ticks_total == 0 {
            return 1.0;
        }
        (self.ticks_total - self.ticks_remaining) as f64 / self.ticks_total as f64
    }
}

/// Summary shown after a surge completes.
#[allow(dead_code)]
pub struct ChronoSurgeSummary {
    pub kills: u64,
    pub levels_gained: u32,
    pub items_equipped: u32,
    pub ticks_completed: u64,
    pub ticks_total: u64,
}
